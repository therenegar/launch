static int boxes_solve_dfs(int depth,int limit,int lastdir)
{
 int d,ox=player_x,oy=player_y,om=moves,op=pushes,nx,ny,bi,ni,pushed;
 static const int dx[4]={0,1,0,-1},dy[4]={-1,0,1,0};
 if(solved()){solve_len=depth;return 1;}if(depth>=limit||++solve_nodes>30000UL)return 0;
 if((solve_nodes&127UL)==0){if((unsigned long)(acc_ticks()-solve_start)>=SOLVE_TICK_BUDGET){solve_abort=2;return 0;}if(acc_key_ready()&&acc_key()==27){solve_abort=1;return 0;}}
 for(d=0;d<4;d++){
   if(depth&&d==((lastdir+2)&3))continue;
   nx=player_x+dx[d];ny=player_y+dy[d];pushed=0;bi=-1;ni=-1;
   if(inside(nx,ny)){bi=at(nx,ny);if(box_at[bi]){int bx=nx+dx[d],by=ny+dy[d];if(inside(bx,by)){ni=at(bx,by);pushed=1;}}}
   if(move_player(dx[d],dy[d])){
     solve_path[depth]=(unsigned char)d;if(boxes_solve_dfs(depth+1,limit,d))return 1;
     /* Exact undo without copying the board. */
     if(pushed&&ni>=0&&bi>=0&&box_at[ni]){box_at[ni]=0;box_at[bi]=1;}
     player_x=ox;player_y=oy;moves=om;pushes=op;
   }
 }
 return 0;
}
